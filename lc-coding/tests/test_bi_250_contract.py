def controlled_asset_and_gh_state() -> tuple[dict, dict]:
    asset = json.loads(
        (bi / "release/loop-contract-identities.json").read_text(encoding="utf-8")
    )
    state = {"repositories": {}}
    for method, contract in LOOP_FILES.items():
        identity = asset["execution_methods"][method]
        files = {}
        for field in ["manifest", "schema", "template"]:
            path = contract[f"{field}_path"]
            body = f"{method}:{field}:formal-release-bytes\n".encode()
            files[path] = base64.b64encode(body).decode()
            identity[f"{field}_sha256"] = hashlib.sha256(body).hexdigest()
        state["repositories"][contract["repository"]] = {
            "main_commit": identity["candidate_commit"],
            "tag_commit": identity["candidate_commit"],
            "tag": f"v{identity['version']}",
            "release_present": True,
            "release_is_draft": False,
            "release_is_prerelease": False,
            "files": files,
        }
    return asset, state


def compatibility_v2_candidate(asset: dict) -> dict:
    candidate = copy.deepcopy(asset)
    if candidate.get("asset_schema") == "LCCODING_BI_COMPATIBILITY_V2":
        assert set(candidate.get("status_adapters", {})) == {"2.6.0", "2.7.0", "2.8.0"}
        return candidate
    candidate["asset_schema"] = "LCCODING_BI_COMPATIBILITY_V2"
    candidate["status_adapters"]["2.7.0"]["compatibility_status"] = "SUPPORTED_LEGACY"
    current = copy.deepcopy(candidate["status_adapters"]["2.7.0"])
    current["status_schema_version"] = "2.8.0"
    current["compatibility_status"] = "CURRENT"
    current["minimum_bi_version"] = "2.8.0"
    current["phase_steps"]["REAL_PRODUCT_INTEGRATION"] = current[
        "phase_steps"
    ].pop("ENGINEERING_RUNS")
    candidate["status_adapters"]["2.8.0"] = current
    return candidate


def compatibility_v1_candidate(asset: dict) -> dict:
    candidate = copy.deepcopy(asset)
    candidate["asset_schema"] = "LCCODING_BI_COMPATIBILITY_V1"
    candidate["status_adapters"].pop("2.8.0", None)
    candidate["status_adapters"]["2.7.0"]["compatibility_status"] = "CURRENT"
    assert set(candidate["status_adapters"]) == {"2.6.0", "2.7.0"}
    return candidate


