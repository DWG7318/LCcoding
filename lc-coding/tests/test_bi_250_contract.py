def run_release_verifier(
    asset: dict | str, host: str, change_state=None
) -> tuple[subprocess.CompletedProcess[str], list[str]]:
    _, state = controlled_asset_and_gh_state()
    if change_state is not None:
        change_state(state)
    with tempfile.TemporaryDirectory(prefix="lccoding-loop-release-") as temporary:
        temp = Path(temporary)
        scripts = temp / "bi/scripts"
        release = temp / "bi/release"
        fake_bin = temp / "bin"
        scripts.mkdir(parents=True)
        release.mkdir(parents=True)
        fake_bin.mkdir()
        (scripts / "verify-loop-releases.ps1").write_text(
            release_gate, encoding="utf-8", newline="\n"
        )
        (release / "loop-contract-identities.json").write_text(
            (json.dumps(asset, indent=2) + "\n") if isinstance(asset, dict) else asset,
            encoding="utf-8",
            newline="\n",
        )
        state_path = temp / "state.json"
        state_path.write_text(json.dumps(state), encoding="utf-8")
        log_path = temp / "gh-calls.jsonl"
        fake_python = fake_bin / "fake_gh.py"
        fake_python.write_text(
            """import base64, json, os, sys
from pathlib import Path
args = sys.argv[1:]
with Path(os.environ['FAKE_GH_LOG']).open('a', encoding='utf-8') as stream:
    stream.write(json.dumps(args) + '\\n')
state = json.loads(Path(os.environ['FAKE_GH_STATE']).read_text(encoding='utf-8'))
repositories = state['repositories']
if args[:1] == ['api'] and len(args) == 2:
    endpoint = args[1]
    for repository, record in repositories.items():
        prefix = f'repos/{repository}/'
        if not endpoint.startswith(prefix):
            continue
        suffix = endpoint[len(prefix):]
        if suffix == 'git/ref/heads/main':
            print(json.dumps({'object': {'type': 'commit', 'sha': record['main_commit']}}))
            raise SystemExit(0)
        if suffix == f'git/ref/tags/{record["tag"]}':
            print(json.dumps({'object': {'type': 'commit', 'sha': record['tag_commit']}}))
            raise SystemExit(0)
        if suffix.startswith('contents/') and '?ref=' in suffix:
            path, commit = suffix[len('contents/'):].split('?ref=', 1)
            if commit == record['tag_commit'] and path in record['files']:
                print(json.dumps({'type': 'file', 'encoding': 'base64', 'content': record['files'][path]}))
                raise SystemExit(0)
elif args[:2] == ['release', 'view'] and '-R' in args:
    tag = args[2]
    repository = args[args.index('-R') + 1]
    record = repositories.get(repository)
    if record and tag == record['tag'] and record.get('release_present', True):
        print(json.dumps({'tagName': record.get('release_tag', tag), 'isDraft': record.get('release_is_draft', False), 'isPrerelease': record.get('release_is_prerelease', False), 'publishedAt': '2026-01-01T00:00:00Z', 'url': f'https://example.invalid/{repository}/{tag}'}))
        raise SystemExit(0)
raise SystemExit(1)
""",
            encoding="utf-8",
            newline="\n",
        )
        (fake_bin / "gh.cmd").write_text(
            f'@"{sys.executable}" "%~dp0fake_gh.py" %*\r\n', encoding="utf-8"
        )
        posix_gh = fake_bin / "gh"
        posix_gh.write_text(
            f"#!{sys.executable}\n"
            "import runpy\n"
            "from pathlib import Path\n"
            'runpy.run_path(str(Path(__file__).with_name("fake_gh.py")), '
            'run_name="__main__")\n',
            encoding="utf-8",
            newline="\n",
        )
        posix_gh.chmod(
            posix_gh.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH
        )
        assert posix_gh.is_file(), "the fake gh must expose a POSIX executable shim"
        assert os.access(posix_gh, os.X_OK), "the POSIX fake gh shim must be executable"
        assert b"\r\n" not in posix_gh.read_bytes(), "the POSIX fake gh shim must use LF"
        environment = os.environ.copy()
        environment["PATH"] = f"{fake_bin}{os.pathsep}{environment['PATH']}"
        environment["FAKE_GH_STATE"] = str(state_path)
        environment["FAKE_GH_LOG"] = str(log_path)
        completed = subprocess.run(
            [
                host,
                "-NoProfile",
                "-NonInteractive",
                "-File",
                str(scripts / "verify-loop-releases.ps1"),
            ],
            text=True,
            encoding="utf-8",
            errors="replace",
            capture_output=True,
            env=environment,
            timeout=30,
        )
        calls = (
            log_path.read_text(encoding="utf-8").splitlines() if log_path.exists() else []
        )
        return completed, calls


